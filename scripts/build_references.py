#!/usr/bin/env python3
"""Validate reference entries and generate list pages and JSON.

Usage:
    python scripts/build_references.py          # validate and write outputs
    python scripts/build_references.py --check  # validate only, fail if outputs are stale
"""
import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REFS = ROOT / "references"

SECTIONS = {
    # folder: (page title, allowed types, intro)
    "resources": ("Resources", {"Resource", "Book", "Article", "Post", "Video", "Technology"},
                  "Books, specs, guides, articles, and videos about Markdown."),
    "tools": ("Tools", {"App", "Technology", "Service"}, "Editors, converters, libraries, and services."),
    "people": ("People", {"Person"}, "People who created, shaped, or teach Markdown."),
    "organizations": ("Organizations", {"Organization"}, "Spec bodies, companies, and projects that shape Markdown."),
}
# Types that often have no single canonical URL.
URL_OPTIONAL = {"Person", "Book"}
STATES = {"draft", "active", "watch", "stale", "broken", "retired"}
REQUIRED = ["type", "slug", "state", "source", "added"]
# Types for documents that aren't reference entries. We define these; see README.md.
DOC_TYPES = {"Readme", "Instructions", "Brainstorm", "Course", "Presentation", "List", "Inbox", "Context", "Exercise", "Cheatsheet", "Reference"}
TEMPLATE_TYPES = {"Resource", "Book", "App", "Person", "Organization"}
SKIP_DIRS = {".git", "node_modules"}
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)


def clean(value):
    """Drop the blank `- ` placeholders the templates use."""
    if isinstance(value, list):
        return [v for v in value if v not in (None, "")]
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    return "" if value is None else value


def load(path, errors):
    text = path.read_text(encoding="utf-8")
    m = FM_RE.match(text)
    if not m:
        errors.append(f"{path}: missing frontmatter")
        return None
    try:
        data = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        errors.append(f"{path}: invalid YAML: {e}")
        return None
    return {k: clean(v) for k, v in data.items()}


def title_of(e):
    if e.get("title"):
        return e["title"]
    name = f"{e.get('first_name', '')} {e.get('last_name', '')}".strip()
    return name or e["slug"]


def collect():
    errors, entries = [], {}
    for folder, (_, allowed_types, _) in SECTIONS.items():
        entries[folder] = []
        for path in sorted((REFS / folder).glob("*.md")):
            e = load(path, errors)
            if e is None:
                continue
            where = path.relative_to(ROOT)
            for field in REQUIRED:
                if not e.get(field):
                    errors.append(f"{where}: missing required field `{field}`")
            if e.get("type") and e["type"] not in allowed_types:
                errors.append(f"{where}: type `{e['type']}` should be one of {sorted(allowed_types)}")
            if not e.get("url") and e.get("type") not in URL_OPTIONAL:
                errors.append(f"{where}: missing required field `url`")
            slug = e.get("slug", "")
            if slug and not SLUG_RE.match(str(slug)):
                errors.append(f"{where}: slug `{slug}` must be lowercase-hyphenated")
            if slug and slug != path.stem:
                errors.append(f"{where}: filename must match slug `{slug}.md`")
            if e.get("state") and e["state"] not in STATES:
                errors.append(f"{where}: state `{e['state']}` not one of {sorted(STATES)}")
            added = e.get("added")
            if added and not re.match(r"^\d{4}-\d{2}-\d{2}$", str(added)):
                errors.append(f"{where}: added must be YYYY-MM-DD")
            e["_path"] = path.relative_to(REFS).as_posix()
            entries[folder].append(e)

    # Cross-references: people/organizations fields must point at real slugs.
    slugs = {f: {e["slug"] for e in es if e.get("slug")} for f, es in entries.items()}
    for folder, es in entries.items():
        for e in es:
            for field, target in (("people", "people"), ("organizations", "organizations")):
                for ref in e.get(field, []) or []:
                    if ref not in slugs[target]:
                        errors.append(f"references/{e['_path']}: `{field}` has unknown slug `{ref}`")
    return entries, errors


def render_list(folder, es):
    title, _, intro = SECTIONS[folder]
    lines = [
        "---",
        "type: List",
        "---",
        "",
        f"# {title}",
        "",
        "<!-- Generated by scripts/build_references.py. Edit the entry files, not this page. -->",
        "",
        f"{intro} {len(es)} entries. Schema: [README.md](README.md).",
        "",
        "| Name | Type | State | Tags | Link |",
        "|:---|:---|:---|:---|:---|",
    ]
    for e in sorted(es, key=lambda e: title_of(e).lower()):
        if e.get("state") == "retired":
            continue
        tags = " ".join(f"`#{t}`" for t in e.get("tags", []) if t != "tool")
        link = f"<{e['url']}>" if e.get("url") else ""
        lines.append(f"| [{title_of(e)}]({e['_path']}) | {e.get('type', '')} | {e.get('state', '')} | {tags} | {link} |")
    return "\n".join(lines) + "\n"


def render_json(entries):
    out = []
    for folder, es in entries.items():
        for e in es:
            item = {k: v for k, v in e.items() if not k.startswith("_")}
            item["id"] = f"{folder}/{e.get('slug')}"
            item["title"] = title_of(e)
            item["path"] = f"references/{e['_path']}"
            out.append(item)
    return json.dumps(sorted(out, key=lambda i: i["id"]), indent=2, ensure_ascii=False) + "\n"


def check_all_docs(entry_paths):
    """Every Markdown file starts with frontmatter whose first field is `type`."""
    errors = []
    for p in sorted(ROOT.rglob("*.md")):
        rel = p.relative_to(ROOT)
        if SKIP_DIRS & set(rel.parts) or (rel.parent.name == "references" and p.stem in SECTIONS):
            continue  # generated lists are checked by the out-of-date check
        m = FM_RE.match(p.read_text(encoding="utf-8"))
        first = m.group(1).splitlines()[0] if m and m.group(1).strip() else ""
        key, _, value = first.partition(":")
        value = value.strip()
        if key != "type" or not value:
            errors.append(f"{rel}: frontmatter must start with `type`")
        elif p in entry_paths:
            continue  # reference entries: types checked per section
        elif rel.parts[0] == "templates" and rel.name != "README.md":
            if value not in TEMPLATE_TYPES:
                errors.append(f"{rel}: type `{value}` should be one of {sorted(TEMPLATE_TYPES)}")
        elif value not in DOC_TYPES:
            errors.append(f"{rel}: type `{value}` should be one of {sorted(DOC_TYPES)}")
    return errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only; fail if generated files are out of date")
    args = ap.parse_args()

    entries, errors = collect()
    errors += check_all_docs({REFS / e["_path"] for es in entries.values() for e in es})
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"\n{len(errors)} problem(s) found.", file=sys.stderr)
        return 1

    outputs = {REFS / f"{folder}.md": render_list(folder, es) for folder, es in entries.items()}
    outputs[REFS / "references.json"] = render_json(entries)

    stale = [p for p, content in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            print("Out of date, run scripts/build_references.py:\n" + "\n".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
    else:
        for p in stale:
            p.write_text(outputs[p], encoding="utf-8", newline="\n")
    total = sum(len(es) for es in entries.values())
    print(f"OK: {total} entries" + ("" if args.check else f", {len(stale)} file(s) written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
